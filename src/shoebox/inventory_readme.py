"""`frame/README.md`: a summary of a sampling frame. Folder names appear; photo file names never do."""

import json
import re
from collections import Counter, defaultdict
from pathlib import Path


def _gb(n: int) -> str:
    return f"{n / 1e9:,.1f}"


def top_folder(relpath: str) -> str:
    """The first folder of a relpath, or the first two under `Pictures`; files at the root give `.`."""
    parts = relpath.split("/")[:-1]
    if not parts:
        return "."
    return "/".join(parts[:2]) if parts[0] == "Pictures" and len(parts) > 1 else parts[0]


def era(date: str | None) -> str:
    if not date:
        return "unknown"
    y = int(date[:4])
    lo = y - y % 5
    return f"{lo}-{lo + 4}"


def _table(head: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out + [""]


def _count_bytes(rows: list[dict], key) -> list[list]:
    n, b = Counter(), Counter()
    for r in rows:
        k = key(r)
        n[k] += 1
        b[k] += r["bytes"] or 0
    return [[k, f"{n[k]:,}", _gb(b[k])] for k in sorted(n, key=lambda k: (-b[k], str(k)))]


def render(frame: Path, listing: Path | None = None) -> str:
    import pyarrow.parquet as pq

    rows = pq.read_table(frame, columns=[
        "source", "person", "synced", "relpath", "ext", "kind", "bytes", "asset_id", "status", "error", "src_kind",
        "date", "date_kind", "colour_guess", "group_id", "group_rule", "dup_n"]).to_pylist()
    if listing is None:
        cand = frame.with_name(frame.name.replace("frame-", "listing-").replace(".parquet", ".json"))
        listing = cand if cand.exists() else None
    log = json.loads(listing.read_text()) if listing else None
    media = [r for r in rows if r["kind"] in ("image", "video")]
    images = [r for r in rows if r["kind"] == "image"]

    out = [f"# Sampling frame `{frame.name}`", "",
           "Generated by `shoebox inventory readme`. Counts are file paths (one row per path); bytes in GB.", ""]
    out += [(f"**{len(rows):,} files, {_gb(sum(r['bytes'] for r in rows))} GB**; "
            f"{len(images):,} images, {len(media) - len(images):,} videos."), ""]

    out += ["## Per source", ""]
    out += _table(["source", "files", "GB"], _count_bytes(rows, lambda r: f"{r['source']} ({r['person']}, "
                                                                          f"{'synced' if r['synced'] else 'not synced'})"))
    out += ["## Per top-level folder", "", "Two levels under `Pictures`.", ""]
    out += _table(["source/folder", "files", "GB"], _count_bytes(rows, lambda r: f"{r['source']}/{top_folder(r['relpath'])}"))
    out += ["## Per kind", ""]
    out += _table(["kind", "files", "GB"], _count_bytes(rows, lambda r: r["kind"]))
    out += ["## Per extension (media)", ""]
    out += _table(["ext", "files", "GB"], _count_bytes(media, lambda r: r["ext"] or "(none)"))

    out += ["## Per era (media)", "",
            "Five-year buckets by best date, excluding scan dates (a scan date is when it was scanned).", ""]
    dated = [r for r in media if r["date_kind"] != "scan"]
    kinds = sorted({r["date_kind"] for r in dated if r["date_kind"]})
    by = defaultdict(Counter)
    for r in dated:
        by[era(r["date"])][r["date_kind"]] += 1
    out += _table(["era", "files", *kinds],
                  [[e, f"{sum(by[e].values()):,}", *(f"{by[e][k]:,}" for k in kinds)] for e in sorted(by)])
    scans = [r for r in media if r["date_kind"] == "scan"]
    out += [f"Scan-dated: {len(scans):,} files.", ""]
    if scans:
        out += _table(["scan era", "files"], [[k, f"{v:,}"] for k, v in
                                              sorted(Counter(era(r['date']) for r in scans).items())])
    out += ["Date kinds: " + ", ".join(f"{k} {v:,}" for k, v in
                                       Counter(r["date_kind"] for r in media).most_common()), ""]

    out += ["## Colour guess (images)", ""]
    out += _table(["colour_guess", "files"], [[k or "(not decoded)", f"{v:,}"] for k, v in
                                              Counter(r["colour_guess"] for r in images).most_common()])

    out += ["## Capture groups", ""]
    groups = defaultdict(set)
    members = Counter()
    for r in rows:
        if r["group_id"]:
            groups[r["group_rule"]].add(r["group_id"])
            members[r["group_rule"]] += 1
    out += _table(["rule", "groups", "member files"], [[k, f"{len(v):,}", f"{members[k]:,}"] for k, v in
                                                       sorted(groups.items())])

    out += ["## Exact duplicates", ""]
    by_id = defaultdict(list)
    for r in media:
        if r["asset_id"]:
            by_id[r["asset_id"]].append(r)
    dups = {k: v for k, v in by_id.items() if len(v) > 1}
    extra = sum(len(v) - 1 for v in dups.values())
    extra_bytes = sum((len(v) - 1) * v[0]["bytes"] for v in dups.values())
    out += [f"{len(dups):,} groups of identical bytes; {extra:,} redundant copies, {_gb(extra_bytes)} GB.", ""]
    pairs = Counter()
    for v in dups.values():
        srcs = sorted({r["source"] for r in v})
        for i, a in enumerate(srcs):
            for b in srcs[i + 1:]:
                pairs[(a, b)] += 1
    if pairs:
        out += _table(["source pair", "shared assets"], [[f"{a} / {b}", f"{n:,}"] for (a, b), n in pairs.items()])

    out += ["## Decode failures", ""]
    errs = [r for r in rows if r["status"] == "error"]
    out += [f"{len(errs):,} files with status `error`.", ""]
    if errs:
        msgs = Counter((r["src_kind"] or r["ext"], _generic(r["error"])) for r in errs)
        out += _table(["src_kind", "error", "files"], [[k, m, f"{n:,}"] for (k, m), n in msgs.most_common(30)])

    if log:
        out += ["## Skips and listing stability", ""]
        skips = Counter()
        lrows = []
        for name, s in log["sources"].items():
            skips.update(s["skips"])
            lrows.append([name, f"{s['folders']:,}", f"{s['listings']:,}", f"{s['unstable_folders']:,}",
                          f"{len(s['errors']):,}"])
        out += _table(["source", "folders", "listings taken", "folders whose listings differed", "walk errors"],
                      lrows)
        out += _table(["skipped", "entries"], [[f"`{k}`", f"{v:,}"] for k, v in skips.most_common()])
        u = log.get("untouched", {})
        out += [(f"Sources-untouched check: {'passed' if u.get('ok') else 'FAILED'} "
                f"({u.get('sample_files', 0)} sampled files hashed, {u.get('folders', 0):,} folder listings)."), ""]
    return "\n".join(out)


def _generic(msg: str | None) -> str:
    """An error message without paths or numbers, so it groups and names no file."""
    msg = re.sub(r"/[^\s:]+", "<path>", msg or "")
    msg = re.sub(r"\d+", "N", msg)
    return msg[:100].replace("|", "/")
